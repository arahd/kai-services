from agent_framework import Content,Message,tool

from logger import logger,get_caller_frame,extras
from llm_helpers import compress_image
from agent_pool_context_helper import current_conv_id

from conversationalservice.service_route_utils import fetch_image_bytes

SERVICE_NAME='KAI_CHATBOT_CONVERSATIONAL_SERVICE'
PROJECT_NAME='KAI'

class ImageFetchPlugin:
    last_search = None
    def __init__(self, conv_id:str,model_name:str):
        extras = {
        'servicename': SERVICE_NAME,
        'functionname': get_caller_frame().f_code.co_name,
        'projectname': PROJECT_NAME,
        'bot_name':'CIBC'
    }
        #self.conv_id = conv_id
        self.aug_source = []
        self.aug_content = ''
        self.total_input_tokens_consumed = 0
        self.total_output_tokens_consumed = 0


    @tool(approval_mode="never_require",
        name="image_fetch",
        description="""
        # Image Fetch
        This tool returns the Image whoes name you passed
        This only works on Images uploaded in this conversation

        **IMPORTANT:** This tool returns Image for your context only. You must analyze, summarize, and synthesize it to provide a natural, conversational response to the user.

        **HOW TO USE:**
        - ONLY use this function when the user asks for something related to an Image they have uploaded for which you need context.
        - This tool only takes name of the image file like 'picture_of_dog.jpeg', 'more cats.png' or '2r4rfedddindfm.jpg' etc.
        - This only handles one image at a time.
        - If you need context for multiple images, call this tool multiple times.
        - This tool returns returns "No image found with that name" if no image is found.
        - This Tool does not return content of Images Generated by you

        **DO NOT use this function when:**
        - You are not sure if the user is referring to a image,
        - When refering to Generated Images 

         **Error handling**
        - If the tool fails or returns inconsistent data, acknowledge briefly and propose next steps""")
    async def fetch_image(self, image_filename: str)->Message:
        """
        Returns the Image whose name you passed.
        The Scope of Images which can be fetched is restricted to images uploaded by user in a conversation
        Args:
            image_filename (str): The Name of the Image that you need.

        """
        extras = {
        'servicename': SERVICE_NAME,
        'functionname': get_caller_frame().f_code.co_name,
        'projectname': PROJECT_NAME,
        'bot_name':'CIBC'
    }
        logger.info(f'Image Fetch Started',extra=extras)
        try:
            image_bytes,image_name = fetch_image_bytes(image_filename=image_filename,conversation_id=current_conv_id.get())
            compressed_image, content_type = compress_image(image_bytes)
            return Message(  role="tool", contents=[
                Content.from_uri(uri=f"data:{content_type};base64,{compressed_image}" , media_type=content_type)
            ])
        except Exception as e:
            logger.exception(f"unknown Exception during image fetch : {e}",extra=extras)
            return Message(  role="tool", contents=[
                Content.from_text("Something went wrong when using the Fetch Image tool")])
